package com.example.qlapp.games

/**
 * 一个方块：在 timeMs 这一刻落到判定线，压在第 column 列。
 * semitone 是绝对半音高度（60 = C4），决定点击时弹哪个音。
 * holdMs 大于 0 表示这是一块「长方块」：按住不放，到 timeMs + holdMs 才能松手。
 */
data class SongBeat(
    val timeMs: Int,
    val column: Int,
    /** 绝对半音高度（60 = C4），-1 表示没测到音高（发声时按 C4 兜底）。 */
    val semitone: Int = -1,
    val holdMs: Int = 0,
) {
    val isHold: Boolean get() = holdMs > 0
}

/**
 * 一首可玩的曲子。
 * audioPath 只是导入歌的来源记录（旧版本会复制原音频）；游戏里不放原声，
 * 玩家按出的钢琴音就是这首歌的旋律。
 */
class Song(
    val id: String,
    val title: String,
    val author: String,
    val beats: List<SongBeat>,
    val audioPath: String? = null,
    val builtin: Boolean = false,
) {

    /**
     * 下落速度（世界坐标单位 / 毫秒）。
     * 用相邻方块间隔的中位数占满一行，再夹在可玩区间里，
     * 免得某首歌有个别极密的音符就把整首歌滚成残影。
     */
    val scrollPxPerMs: Float = run {
        val gaps = beats.zipWithNext { a, b -> b.timeMs - a.timeMs }.sorted()
        val median = gaps.getOrNull(gaps.size / 2) ?: 500
        PianoGame.ROW_HEIGHT / median.coerceIn(240, 900)
    }

    /** 最后一个方块落地后多留一点余量，让收尾音能放完。 */
    val durationMs: Int = (beats.lastOrNull()?.timeMs ?: 0) + 1600

    val noteCount: Int get() = beats.size

    /** 需要长按的长方块数量，选曲界面会标出来。 */
    val holdCount: Int get() = beats.count { it.isHold }

    /** 大约要弹多久，选曲界面显示用。 */
    val lengthLabel: String get() {
        val total = durationMs / 1000
        return "%d:%02d".format(total / 60, total % 60)
    }
}

/** 音高均匀分成 4 档：低音在左，高音在右。 */
private fun columnOf(semitone: Int, low: Int, high: Int): Int {
    if (high <= low) return ((semitone % 4) + 4) % 4
    val t = (semitone - low).toFloat() / (high - low).toFloat()
    return (t * 3.999f).toInt().coerceIn(0, 3)
}

/**
 * 从「槽位:半音:槽数」的打包数据生成一首歌：
 * 每个八分音符槽一个音，空槽就是休止；长度 ≥3 槽的长音自动做成长方块。
 * 扒带定制的曲子都用这个格式，一行一个音，改起来直观。
 */
private fun grid(id: String, title: String, author: String, slotMs: Int, packed: String): Song {
    val rows = packed.trim().split(Regex("\\s+")).filter { it.isNotBlank() }.map { line ->
        val parts = line.split(":")
        Triple(parts[0].toInt(), parts[1].toInt(), parts[2].toInt())
    }
    val low = rows.minOf { it.second } - 1
    val high = rows.maxOf { it.second } + 1
    val beats = rows.map { (slot, semitone, len) ->
        val hold = if (len >= 3) (len * slotMs * 0.8f).toInt().coerceAtMost(2400) else 0
        SongBeat(2600 + slot * slotMs, columnOf(semitone, low, high), semitone, hold)
    }
    return Song(id, title, author, beats, builtin = true)
}

private fun melody(
    id: String,
    title: String,
    author: String,
    bpm: Float,
    notes: IntArray,
    durations: IntArray = IntArray(notes.size) { 2 },
): Song {
    require(notes.size == durations.size) { "音符和时值数量必须一致" }
    val low = notes.min() - 1
    val high = notes.max() + 1
    val msPerUnit = 30000f / bpm // 一个时值单位 = 半拍
    var cursor = 2600f // 开头留出准备时间
    val beats = notes.indices.map { i ->
        val length = durations[i] * msPerUnit
        // 二分音符以上的长音（时值 ≥ 4）画成需要按住的长方块，留一点空隙免得和下一段连上。
        val hold = if (durations[i] >= 4) (length * 0.74f).toInt() else 0
        val beat = SongBeat(cursor.toInt(), columnOf(notes[i], low, high), notes[i], hold)
        cursor += length
        beat
    }
    return Song(id, title, author, beats, builtin = true)
}

